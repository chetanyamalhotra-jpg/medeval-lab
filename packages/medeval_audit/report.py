@dataclass
class DatasetAudit:
    """Complete audit of one dataset split."""

    dataset: str
    split: str
    n_items: int
    licence: str
    licence_evidence: str
    repo_id: str
    strategy: str
    source_detail: str
    fingerprint: str
    duplicates: DuplicateReport
    answer_key: AnswerKeyReport
    contamination: ContaminationReport
    notes: list[str]
    toolkit_version: str = __version__
    items_version: str = ITEMS_VERSION

    def as_dict(self) -> dict[str, Any]:
        return {
            "dataset": self.dataset,
            "split": self.split,
            "n_items": self.n_items,
            "licence": self.licence,
            "licence_evidence": self.licence_evidence,
            "repo_id": self.repo_id,
            "load_strategy": self.strategy,
            "source_detail": self.source_detail,
            "fingerprint": self.fingerprint,
            "duplicates": self.duplicates.as_dict(),
            "answer_key": self.answer_key.as_dict(),
            "contamination": self.contamination.as_dict(),
            "notes": self.notes,
            "toolkit_version": self.toolkit_version,
            "items_version": self.items_version,
        }

    @property
    def flagged_item_ids(self) -> list[str]:
        flagged = set(self.answer_key.flagged_item_ids)
        flagged.update(self.duplicates.flagged_item_ids)
        flagged.update(self.contamination.answer_in_stem_ids)
        return sorted(flagged)


def audit_split(
    loaded: LoadedSplit,
    *,
    near_dup_threshold: float = 0.85,
    other: Sequence[AuditRecord] | None = None,
    other_name: str = "",
) -> DatasetAudit:
    """Audit one loaded split. Nothing is removed or rewritten."""
    duplicates = find_duplicates(loaded.records, threshold=near_dup_threshold)
    answer_key = check_answer_key(loaded.records)
    contamination = run_screens(loaded.records, other, other_name=other_name)
    fingerprint = dataset_fingerprint(
        [
            {
                "id": record.item_id,
                "question": record.question,
                "options": list(record.options),
                "gold_index": record.gold_index,
            }
            for record in loaded.records
        ]
    )
    notes = [loaded.notes] if loaded.notes else []
    if loaded.strategy != "datasets.load_dataset":
        notes.append(
            f"loaded with fallback strategy '{loaded.strategy}'; the primary "
            "datasets.load_dataset path was unavailable in this environment"
        )
    return DatasetAudit(
        dataset=loaded.spec.key,
        split=loaded.split,
        n_items=loaded.n,
        licence=loaded.spec.licence,
        licence_evidence=loaded.spec.licence_evidence,
        repo_id=loaded.spec.repo_id,
        strategy=loaded.strategy,
        source_detail=loaded.source_detail,
        fingerprint=fingerprint,
        duplicates=duplicates,
        answer_key=answer_key,
        contamination=contamination,
        notes=notes,
    )


def _pct(value: float) -> str:
    if value != value:  # NaN
        return "n/a"
    return f"{100 * value:.2f}%"


def render_markdown(audits: Sequence[DatasetAudit]) -> str:
    """Human-readable audit summary for the report."""
    lines: list[str] = []
    lines.append("# Benchmark audit report")
    lines.append("")
    lines.append(
        "Generated by `medeval audit`. Items are flagged, never modified; the audit "
        "does not assert that any item is clinically wrong."
    )
    lines.append("")
    lines.append("| dataset | split | items | licence | key base | missing key | out of range | exact dup groups | near dup groups | cross-benchmark matches |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for audit in audits:
        lines.append(
            f"| {audit.dataset} | {audit.split} | {audit.n_items} | {audit.licence} | {audit.answer_key.index_base} | {audit.answer_key.n_missing_gold} | {audit.answer_key.n_out_of_range} | {audit.duplicates.n_exact_groups} | {audit.duplicates.n_near_groups} | {len(audit.contamination.cross_dataset_pairs)} |"
        )
    lines.append("")

    for audit in audits:
        key = audit.answer_key
        lines.append(f"## {audit.dataset} / {audit.split}")
        lines.append("")
        lines.append(f"- Rows audited: **{audit.n_items}** (content fingerprint `{audit.fingerprint[:16]}`)")
        lines.append(f"- Licence: `{audit.licence}` — evidence: {audit.licence_evidence}")
        lines.append(f"- Load strategy: `{audit.strategy}`")
        lines.append(f"- Gold-index base: **{key.index_base}** ({key.index_base_evidence})")
        lines.append(
            f"- Key distribution: {key.gold_distribution}; uniformity p = "
            f"{'n/a' if key.uniformity_p_value is None else f'{key.uniformity_p_value:.4g}'}"
        )
        lines.append(
            f"- Shortcut baselines: always-first = {_pct(key.always_first_accuracy)}, "
            f"longest-option = {_pct(key.longest_option_accuracy)}"
        )
        lines.append(
            f"- Mean option length: gold {key.mean_gold_option_length:.1f} chars vs "
            f"others {key.mean_other_option_length:.1f} chars"
        )
        lines.append(
            f"- Duplicates: exact {audit.duplicates.n_exact_groups}, near {audit.duplicates.n_near_groups}, "
            f"shared option sets {audit.duplicates.n_option_set_groups}"
        )
        lines.append(
            f"- Contamination screens: answer-in-stem {_pct(audit.contamination.answer_in_stem_rate)}; "
            f"cross-benchmark pairs {len(audit.contamination.cross_dataset_pairs)}"
        )
        if key.conflicting_key_details:
            lines.append(f"- Conflicting key columns: {len(key.conflicting_key_ids)} item(s)")
        if key.notes:
            for note in key.notes:
                lines.append(f"- NOTE: {note}")
        if audit.notes:
            for note in audit.notes:
                lines.append(f"- NOTE: {note}")
        lines.append(f"- Flagged item ids: {len(audit.flagged_item_ids)} (listed in the JSON report)")
        lines.append("")
    return "\n".join(lines)


def write_report(
    audits: Sequence[DatasetAudit],
    out_dir: Path,
    *,
    skipped: Sequence[dict[str, str]] | None = None,
) -> tuple[Path, Path]:
    """Write JSON and Markdown audit reports; returns their paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    payload = {
        "toolkit_version": __version__,
        "items_version": ITEMS_VERSION,
        "datasets": [audit.as_dict() for audit in audits],
        "skipped": list(skipped or []),
    }
    json_path = out_dir / "audit_report.json"
    md_path = out_dir / "audit_report.md"
    json_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    markdown = render_markdown(audits)
    if skipped:
        markdown += "\n## Skipped\n\n"
        for entry in skipped:
            markdown += f"- `{entry.get('dataset')}`: {entry.get('reason')}\n"
    md_path.write_text(markdown, encoding="utf-8")
    write_datasets_registry(audits, out_dir / "datasets.csv")
    return json_path, md_path


def write_datasets_registry(audits: Sequence[DatasetAudit], path: Path) -> Path:
    """Write the per-dataset licence and fingerprint registry."""
    path.parent.mkdir(parents=True, exist_ok=True)
    columns = [
        "dataset",
        "repo_id",
        "split_audited",
        "n_items",
        "licence",
        "licence_evidence",
        "content_fingerprint",
        "load_strategy",
        "notes",
    ]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        for audit in audits:
            writer.writerow(
                {
                    "dataset": audit.dataset,
                    "repo_id": audit.repo_id,
                    "split_audited": audit.split,
                    "n_items": audit.n_items,
                    "licence": audit.licence,
                    "licence_evidence": audit.licence_evidence,
                    "content_fingerprint": audit.fingerprint,
                    "load_strategy": audit.strategy,
                    "notes": " | ".join(audit.notes)[:300],
                }
            )
    return path


def format_markdown(audits: Sequence[DatasetAudit]) -> str:
    """Alias kept for readability at call sites."""
    return render_markdown(audits)
