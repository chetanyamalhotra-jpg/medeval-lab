"""A built-in synthetic sample for dry runs when the real data is absent.

A dry run exists to prove the *pipeline* works: sampling, prompting, parsing,
scoring, reporting. It does not need MedQA for that, and it must not fail just
because the ``datasets`` package, the cache or the network is missing. When the
real data is not available during a dry run, the runner falls back to this sample
and labels every artefact **PIPELINE TEST ONLY** — the items are fabricated, so no
number from them describes any model or any benchmark.

The sample is deliberately larger than one staged Experiment 003 run needs
(420 items: screening can find 100 hard items, leave 40+ controls, and keep
enough margin for the pilot). Item ids carry the ``synth-`` prefix so they can
never collide with a real MedQA id (``dev-00001``) or with Experiment 002's
records, which is what made the exclusion list eat the whole sample in v0.4.1.

A *real* run never falls back: it stops with a blocked status and the exact
command to fetch the data.
"""

from __future__ import annotations

from medeval_study.datasets import DATASET_LICENCES, DatasetBundle, DatasetLicence
from medeval_study.models import McqItem

__all__ = [
    "SYNTHETIC_DATASET_KEY",
    "SYNTHETIC_SAMPLE_SIZE",
    "builtin_synthetic_bundle",
    "fetch_command",
]

#: Registered licence key for the built-in sample.
SYNTHETIC_DATASET_KEY = "synthetic_builtin"

#: Large enough for one full staged Experiment 003 dry run (100 hard + 40 control
#: with margin for the pilot and for items excluded by an earlier experiment).
SYNTHETIC_SAMPLE_SIZE = 420

_TOPICS = (
    "hypertension", "asthma", "diabetes", "sepsis", "anaemia", "thyroid disease",
    "pneumonia", "migraine", "cirrhosis", "renal failure", "meningitis", "gout",
    "heart failure", "peptic ulcer disease", "varicella", "rheumatoid arthritis",
)

_QUESTIONS = (
    "A synthetic patient presents with findings described for {topic}. Considering the "
    "options below, which single statement best matches a teaching point about {topic}?",
    "In a fabricated clinical vignette about {topic}, which option would a guideline "
    "most likely recommend first?",
    "A synthetic examination question on {topic} asks for the most appropriate next "
    "step. Which option is best supported by the teaching material?",
    "Which of the following statements about {topic} is the most accurate in this "
    "entirely synthetic question?",
    "A fabricated case about {topic} gives four plausible actions. Which one is the "
    "usual first-line answer in teaching material?",
)

_OPTIONS = (
    ("Increase the dose", "Reduce the dose", "Stop the drug", "No change needed"),
    ("Start first-line therapy", "Start second-line therapy", "Observe and review", "Refer urgently"),
    ("Order the confirmatory test", "Order a screening test", "Repeat the test later", "Treat empirically"),
    ("Explain the finding", "Repeat the measurement", "Ignore the finding", "Escalate to surgery"),
    ("Admit for observation", "Discharge with follow-up", "Start antibiotics", "Arrange imaging first"),
)

_PLAUSIBLE = ("yes", "no", "uncertain", "not reported")

#: The built-in sample's licence, registered at import time so status listings
#: and the app can show it without generating an item first.
SYNTHETIC_LICENCE = DatasetLicence(
    key=SYNTHETIC_DATASET_KEY,
    hf_repo="(built into medeval-lab)",
    licence="synthetic; no third-party content",
    licence_evidence="generated by medeval-lab itself",
    redistribute=True,
    attribution="medeval-lab",
)
DATASET_LICENCES[SYNTHETIC_DATASET_KEY] = SYNTHETIC_LICENCE


def builtin_synthetic_bundle(*, n: int = SYNTHETIC_SAMPLE_SIZE, seed: int = 20260101) -> DatasetBundle:
    """``n`` fabricated four-option items, deterministic for a seed.

    Item ids are ``synth-<seed>-<index>``: they cannot collide with MedQA's
    ``dev-#####`` ids or with anything an earlier experiment recorded, so a
    pre-registered exclusion list can never empty the sample.
    """
    import random

    rng = random.Random(seed)
    total = max(1, n)
    items: list[McqItem] = []
    for index in range(total):
        topic = _TOPICS[index % len(_TOPICS)]
        question = _QUESTIONS[index % len(_QUESTIONS)].format(topic=topic)
        # The question must be long enough for the loader's validity rule.
        question = (
            f"{question} Synthetic item {index + 1} of {total}; this text is fabricated "
            "for pipeline tests only."
        )
        option_texts = _OPTIONS[index % len(_OPTIONS)]
        letters = ("A", "B", "C", "D")
        key_index = index % 4
        items.append(
            McqItem(
                item_id=f"synth-{seed}-{index:04d}",
                question=question,
                options={letters[i]: option_texts[i] for i in range(4)},
                key_letter=letters[key_index],
                key_text=option_texts[key_index],
                dataset=SYNTHETIC_DATASET_KEY,
                split="builtin",
                row_index=index,
                meta={"plausible_distractor": rng.choice(_PLAUSIBLE)},
            )
        )
    return DatasetBundle(
        items=tuple(items),
        licence=SYNTHETIC_LICENCE,
        dataset=SYNTHETIC_DATASET_KEY,
        split="builtin",
        strategy="synthetic-builtin",
        source_detail="built-in synthetic sample: fabricated items, no benchmark content",
        n_raw_rows=total,
        n_dropped=0,
        notes=(
            "PIPELINE TEST ONLY: fabricated items built into the app because the real dataset "
            "was unavailable. Nothing here describes a model, a benchmark or a patient."
        ),
    )


def fetch_command(dataset: str) -> str:
    """The exact command a real run needs when the data is missing."""
    return f".\\.venv\\Scripts\\python.exe -m medeval data fetch {dataset}"
